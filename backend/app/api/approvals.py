from datetime import datetime
from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session
from typing import List

from app.database import get_db
from app.models.agent import ApprovalRequest
from app.models.user import User
from app.schemas.approval import ApprovalActionRequest, ApprovalRequestResponse
from app.services.auth_service import get_current_user

router = APIRouter(prefix="/approvals", tags=["Human-in-the-Loop Governance"])

@router.get("", response_model=List[ApprovalRequestResponse])
def get_all_approvals(
    status_filter: str = None,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Lists all consequential business decisions generated by Strategy Agent
    awaiting or completed by Human Manager review.
    """
    query = db.query(ApprovalRequest)
    if status_filter:
        query = query.filter(ApprovalRequest.status == status_filter)
    return query.order_by(ApprovalRequest.id.desc()).all()

@router.get("/{approval_id}", response_model=ApprovalRequestResponse)
def get_approval_detail(
    approval_id: int,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Retrieve details, financial impact, and verification proof for an approval item."""
    item = db.query(ApprovalRequest).filter(ApprovalRequest.id == approval_id).first()
    if not item:
        raise HTTPException(status_code=404, detail="Approval request not found.")
    return item

@router.post("/{approval_id}/action", response_model=ApprovalRequestResponse)
def review_approval_request(
    approval_id: int,
    action: ApprovalActionRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Human-in-the-loop review: Authorized Business Manager approves or rejects
    the proposed consequential business action. Records immutable decision log.
    Enforces RBAC: Only 'business_manager' or 'admin' roles are permitted.
    """
    if current_user.role not in ["admin", "business_manager"]:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Forbidden: Only Business Managers and Administrators have authority to sign off on consequential business actions."
        )

    item = db.query(ApprovalRequest).filter(ApprovalRequest.id == approval_id).first()
    if not item:
        raise HTTPException(status_code=404, detail="Approval request not found.")

    if action.decision not in ["Approved", "Rejected"]:
        raise HTTPException(status_code=400, detail="Decision must be 'Approved' or 'Rejected'")

    item.status = action.decision
    item.reviewed_by = f"{current_user.full_name} ({current_user.role})"
    item.review_notes = action.review_notes
    item.reviewed_at = datetime.utcnow()

    db.commit()
    db.refresh(item)
    return item
